// ============================================================================
// jest.coverage.config.js — 비즈니스 로직 커버리지 게이트
// ----------------------------------------------------------------------------
// CLAUDE.md Iron Law 의 "새 코드 테스트 커버리지 ≥ 60%" 는 지금까지 **문서에만** 있었다
// (jest.config.js 에 coverageThreshold 가 없어 아무도 집행하지 않았다 — 2026-07-26 출시
// 심사 B-15). 집행되지 않는 규칙은 규칙이 아니다. 특히 혼자 개발 + PR 리뷰가 없는 구조에서
// 게이트는 유일한 심판이다.
//
//   npm run test:coverage
//
// ── 왜 lib/ 만 재는가 ────────────────────────────────────────────────────────
// Iron Law 가 겨냥하는 대상이 "비즈니스 로직(거리·페이스 계산·필터)은 순수 함수로 분리"
// 이기 때문이다. 2,300줄짜리 App.tsx 같은 화면 코드까지 한 숫자로 묶으면 임계가 의미를
// 잃는다(무엇이 나빠졌는지 가리키지 못한다).
//
// ── 왜 로직 스위트만 도는가 ──────────────────────────────────────────────────
// 화면 렌더 스위트를 커버리지 계측과 함께 돌리면 jest 워커가 죽는다(--maxWorkers=2 ·
// --runInBand 모두 재현 — react-test-renderer + 계측의 메모리 압력). 그래서 순수 로직
// 스위트(__tests__/lib · tests/acceptance)만 돌린다. 화면 테스트가 추가로 거치는 lib 경로는
// 세지 않으므로 이 수치는 **보수적인 하한**이다 — 실제 커버리지는 이보다 높다.
//
// ── 임계값의 근거 ────────────────────────────────────────────────────────────
// 2026-07-27 실측: statements 85.72 · branches 76.99 · functions 85.71 · lines 88.63.
// 임계는 그보다 2~3%p 낮게 잡는다 — 일상적인 리팩터로는 안 깨지고, 테스트 없는 큰 코드가
// 들어오면 깨지는 자리. **올릴 수는 있어도 내리지는 않는다**(내리려면 이유를 남길 것).
// ============================================================================
