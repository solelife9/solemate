// ============================================================================
// lib/goalTier.ts — 주간 목표 '난이도' 라벨 (순수)
// ----------------------------------------------------------------------------
// 주간 목표 거리(km)가 클수록 야심찬 목표 → 난이도 라벨이 입문→정예로 올라간다.
// 애플 절제(사용자 확정 2026-07-05): 링은 단색(보라)로 두고, 난이도는 '색'이 아니라
// '라벨 텍스트'가 말한다 — 색 남발(게임 느낌) 없이 의미만. 색 결정은 UI(단일 보라).
// 임계(실제 러너 주간 거리): 입문<15 · 꾸준15~29 · 도전30~49 · 열정50~79 · 정예80+.
// 참고: 프로는 주 160~220km.
// ============================================================================

export interface GoalTier {
  key: 'start' | 'steady' | 'push' | 'fire' | 'elite';
  label: string;
}

/** 주간 목표 거리(km) → 난이도 티어(라벨). 비정상 입력은 입문으로. */
export function weeklyGoalTier(km: number): GoalTier {
  const k = Number.isFinite(km) ? km : 0;
  if (k >= 80) return {key: 'elite', label: '정예'};
  if (k >= 50) return {key: 'fire', label: '열정'};
  if (k >= 30) return {key: 'push', label: '도전'};
  if (k >= 15) return {key: 'steady', label: '꾸준'};
  return {key: 'start', label: '입문'};
}
