/**
 * 월간 랭킹(리더보드) 엔트리를 Firestore `leaderboards/{ym}/entries/{uid}` 에 발행할지.
 *
 * **false 인 이유 (2026-07-29 감사):**
 *  1) 리더보드를 볼 화면 진입점이 없다. `App.tsx` 는 ProgressionScreen 에
 *     `onOpenHallOfFame` 을 주입하지 않고, `setShowHallOfFame(true)` 를 부르는 코드도
 *     없다 — 즉 사용자는 이 기능의 존재조차 모른다.
 *  2) 그런데 발행은 클라우드 동기마다 돌아, **닉네임·월간 거리·일관성 점수**가 다른
 *     로그인 사용자 전원이 읽을 수 있는 컬렉션에 쌓였다.
 *  3) 동의를 받은 적이 없고, 개인정보 처리방침에도 '다른 이용자에게 공개된다'는
 *     고지가 없다.
 *
 * **켜는 조건 (1.1 예정):** 랭킹 화면 진입점 복원 + 공개 범위에 대한 **명시적 사용자
 * 동의(옵트인)** + 처리방침에 제3자 공개 조항 반영. 셋이 다 되기 전에는 켜지 않는다.
 *
 * 발행 코드(`lib/progression/firestoreRankingStore.publishMyRanking`)와 화면
 * (`HallOfFameScreen.rn.tsx`)은 **그대로 남겨둔다** — 되살릴 때 이 값만 true 로 바꾼다.
 */
export const LEADERBOARD_PUBLISH_ENABLED = false;

/**
 * 원격 푸시(FCM) 사용 여부 — 서버가 사용자 폰으로 밀어 보내는 알림.
 *
 * **false = 지금은 쓰지 않는다(2026-07-30 민우님 결정).**
 *
 * 왜 안 쓰는가: 보낼 내용이 없다. 앱의 알림 두 종류는 원격 푸시가 필요 없다 —
 *   · 러닝 리마인더 → 폰이 스스로 예약하는 **로컬 알림**(lib/localReminder). 서버 불필요.
 *   · 교체 임박·주간 목표 → 앱을 열 때 계산해 보여준다. 오히려 이게 정확하다(미리 예약해
 *     두면 그 사이 상황이 바뀌어 틀린 알림이 된다).
 * 원격 푸시가 필요해지는 건 **서버만 아는 일**을 알릴 때다: 소셜(친구·챌린지), 운영 공지,
 * 서버가 계산하는 리캡. 셋 다 아직 없다.
 *
 * 끄면 무엇이 달라지나: **FCM 토큰을 아예 받지 않는다.** 안 쓸 토큰을 받아 저장하면
 * 기기 식별자를 목적 없이 보관하는 것이라 개인정보 최소수집 원칙에 어긋난다(처리방침에서
 * '푸시 토큰' 항목을 뺀 이유). 알림 **권한**은 계속 요청한다 — 로컬 알림에 필요하다.
 *
 * 켜는 조건: 위 세 용도 중 하나가 실제로 생기고, 토큰을 받을 서버 엔드포인트가 준비될 때
 * (FCM_REGISTER_ENDPOINT). 그때 이 값을 true 로 바꾼다 — 배선은 그대로 남겨뒀다.
 */
export const REMOTE_PUSH_ENABLED = false;
