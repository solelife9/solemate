// lib/runCache.ts — 부팅 캐시에 넣을 런 레코드 형태 결정(순수)
// ----------------------------------------------------------------------------
// GPS 경로의 집은 사이드키 route_<id> 하나다(2026-07-26 감사 F-08). 예전엔 같은 경로가
// 두 벌 있었다 — 사이드키와, 부팅 캐시 배열 안의 레코드. 경로는 런당 수 KB 라 캐시가
// '런 수 × 경로 크기'로 커졌고, 런을 한 건 저장·삭제할 때마다 그 배열 **전체**를
// 파싱·재직렬화했다(3년 주4회면 600건 — 쓸수록 느려지는 구조).
//
// 다만 '빼기'만 하면 데이터가 유실된다. 메모리 레코드의 route 는 **클라우드 동기의 정본**
// 이라(재설치·기기변경에도 지도가 남는 이유), 되채우지 않으면 빈 route 가 push 되어
// 원격 경로를 덮어 지운다. 그래서 '빼기'와 '되채우기(부팅 시 사이드키 → 메모리)'는 한 쌍이다.
//
// 이 파일은 그 규칙 중 **순수한 결정 부분**만 담는다(저장소 접근 없음 — App 이 담당).
// ============================================================================

/** 캐시에 넣을 런 레코드 — 경로만 제거한 사본(원본 불변). route 가 없으면 그대로 돌려준다. */
export function cacheableRun<T>(r: T): T {
  const rec = r as any;
  if (!rec || typeof rec !== 'object' || !rec.route) return r;
  const {route: _dropped, ...rest} = rec;
  void _dropped;
  return rest as T;
}

/**
 * 저장 직후 캐시에 넣을 레코드를 정한다.
 *
 * `sidecarOk === false` 는 사이드키(route_<id>) 쓰기가 **실패**했다는 뜻이다. 그때는
 * 경로의 로컬 사본이 하나도 남지 않으므로(캐시는 경로를 빼고, 사이드키는 실패) 예외적으로
 * 캐시에 경로를 남긴다 — 캐시가 무거워지는 대가로 유실을 막는다. 다음 디바운스 캐시
 * 쓰기에서 ensureRouteSidecars 가 사이드키를 다시 시도해 정상 형태로 돌아간다.
 *
 * 예전 코드는 사이드키 실패를 그냥 삼켰고, 그 결과 디스크가 꽉 찬 기기에서 경로가
 * 조용히 사라졌다(2026-07-27 F-08 후속 수정).
 */
export function cacheEntryForSave<T>(run: T, sidecarOk: boolean): T {
  const rec = run as any;
  const hasRoute = !!(rec && typeof rec === 'object' && rec.route);
  return hasRoute && !sidecarOk ? run : cacheableRun(run);
}
