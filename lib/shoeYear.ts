// ============================================================================
// lib/shoeYear.ts — 출시연도 비교 (순수). "모른다"를 "오래됐다"로 읽지 않는다.
// ============================================================================
// **왜 있는가(2026-08-08).** 카탈로그 618켤레 중 **427(69%)** 에 출시연도가 없다.
// 그런데 레거시 변환이 `year: s.year ?? 0` 으로 결손을 **0** 으로 메우고 있었고,
// 정렬은 전부 `b.year - a.year`(최신 먼저)였다. 결과:
//
//     연도를 모르는 신발 = 0년 = **가장 오래된 신발**
//
// 그래서 '다음 신발' 추천과 제휴 링크에서 **카탈로그의 69% 가 구조적으로 맨 뒤로**
// 밀렸다. 개선 폭이 같은 후보들 사이에서 연도 미상은 언제나 졌다.
//
// 이건 데이터 결손이 아니라 **결손을 값으로 취급한 버그**다. 연도를 427건 찾아 채우는
// 것은 별개의 긴 작업이고, 채우기 전에도 이 왜곡은 없어야 한다 —
// **모른다는 것은 오래됐다는 뜻이 아니다**(MISSION.md Truth only).
//
// ── 그래서 어떻게 비교하나 ───────────────────────────────────────────────────
// 한쪽이라도 연도를 모르면 **연도로 순서를 정하지 않는다**(0 을 돌려 다음 tie-break 로
// 넘긴다). "A 가 B 보다 최신이다"라고 말할 근거가 없을 때 말하지 않는 것이다.
// 둘 다 알면 최신이 앞이다(원래 의도 그대로).
//
// 대안으로 '미상을 중간값으로 치환'도 생각했지만 그건 없는 값을 지어내는 쪽이라 버렸다.
// ============================================================================

/**
 * 연도 미상 센티널. 레거시 변환(`data/shoeModels.ts`)이 결손을 이 값으로 채운다.
 *
 * ⚠️ 센티널을 **숫자처럼 쓰면 안 된다** — 그게 이 파일이 생긴 이유다.
 * 비교는 반드시 아래 `compareNewerFirst` 를 거친다.
 */
export const YEAR_UNKNOWN = 0;

/** 쓸 수 있는 연도인가. 0·음수·NaN·누락은 전부 '모름'. */
export function isYearKnown(y: number | null | undefined): boolean {
  return typeof y === 'number' && Number.isFinite(y) && y > YEAR_UNKNOWN;
}

/**
 * 최신 먼저 정렬용 비교자. **한쪽이라도 모르면 0**(무승부 → 다음 tie-break 로).
 *
 * ```ts
 * list.sort((a, b) => compareNewerFirst(a.year, b.year) || a.model.localeCompare(b.model));
 * ```
 */
export function compareNewerFirst(
  a: number | null | undefined,
  b: number | null | undefined,
): number {
  if (!isYearKnown(a) || !isYearKnown(b)) return 0;
  return (b as number) - (a as number);
}
